#!/usr/bin/env node
// OpenPlayX UI kit builder/checker. Lives inside ui/ so every synced copy can verify itself.
//   node ui/kit.mjs          regenerate ui/ui-kit.mjs and ui/manifest.json
//   node ui/kit.mjs --check  fail if any kit file differs from ui/manifest.json
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,readdirSync,statSync} from 'node:fs';
import {join,relative,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=dirname(fileURLToPath(import.meta.url));
const generated=new Set(['manifest.json','ui-kit.mjs']);
const files=(dir=root)=>readdirSync(dir).flatMap(name=>{const path=join(dir,name);return statSync(path).isDirectory()?files(path):[relative(root,path).split('\\').join('/')];}).filter(name=>!generated.has(name)).sort();
const sha=text=>createHash('sha256').update(text).digest('hex');
const read=name=>readFileSync(join(root,name),'utf8');
const kitModule=()=>[
  '// Generated by ui/kit.mjs from the files next to it. Do not edit.',
  'export const basecoatCSS='+JSON.stringify(read('vendor/basecoat/basecoat.cdn.min.css'))+';',
  'export const themeCSS='+JSON.stringify(read('opx-theme.css'))+';',
  'export const themeJS='+JSON.stringify(read('opx-theme.js'))+';',
  'export const i18nJS='+JSON.stringify(read('opx-i18n.js'))+';',
  'export const logoSVG='+JSON.stringify(read('opx-logo.svg').trim())+';',
  ''
].join('\n');
const manifest=()=>{const module=kitModule();return JSON.stringify({kit:'openplayx-ui',basecoat:'basecoat-css@1.1.0',files:Object.fromEntries([...files().map(name=>[name,sha(read(name))]),['ui-kit.mjs',sha(module)]])},null,2)+'\n';};

if(process.argv.includes('--check')){
  const expected=JSON.parse(read('manifest.json')).files,actual=JSON.parse(manifest()).files,problems=[];
  for(const name of new Set([...Object.keys(expected),...Object.keys(actual)]))if(expected[name]!==actual[name])problems.push(name);
  if(read('ui-kit.mjs')!==kitModule())problems.push('ui-kit.mjs (stale)');
  if(problems.length){console.error('UI kit out of sync: '+problems.join(', ')+'\nEdit openplayx/web ui/ and run node scripts/sync-ui.mjs.');process.exit(1);}
  console.log('UI kit OK ('+Object.keys(actual).length+' files)');
}else{
  writeFileSync(join(root,'ui-kit.mjs'),kitModule());
  writeFileSync(join(root,'manifest.json'),manifest());
  console.log('UI kit regenerated');
}
